"""Write a clothing pack's add-on mod folder: <pack>/dist/<name>/ (see tools/vc_pack.py, docs/MAKING_CLOTHING.md).

VC_PACK=<pack folder> python tools/make_mod.py

  ModInfo.xml
  Config/items.xml          SDCS model data per item; new items are created (Extends an existing clothing item)
  Config/Localization.txt   names / descriptions of new items
  Config/<anything>.xml     copied from <pack>/Config/ (recipes, loot, ...)
  Resources/<name>.unity3d  from unity/BundleOut/
  README.txt

The add-on has no DLL: Visible Clothing (installed alongside) hides the clothing under armor, swaps in the game's
shader and fits hats to every head.
"""
import os
import shutil
import sys
from xml.sax.saxutils import quoteattr

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import vc_pack

if not vc_pack.PACK:
    sys.exit("set VC_PACK=<pack folder> (the base mod's XML is hand-written: Mod/VisibleClothing/Config/items.xml)")

P = vc_pack.PACK
NAME = vc_pack.NAME
DIST = vc_pack.DIST
BUNDLE_FILE = NAME + ".unity3d"


def sdcs(it):
    part = vc_pack.PART_OF_KIND[it["kind"]]
    rows = [("Prefab", f"#@modfolder:Resources/{BUNDLE_FILE}?gear{{sex}}{it['id']}"),
            ("TransformName", part),
            ("Excludes", it.get("excludes") or "")]
    if it.get("hair_mask"):
        rows.append(("HairMaskType", it["hair_mask"]))
    if it.get("facial_hair_mask"):
        rows.append(("FacialHairMaskType", it["facial_hair_mask"]))
    body = "\n".join(f'\t\t\t<property name="{k}" value={quoteattr(v)}/>' for k, v in rows)
    return f'\t\t<property class="SDCS">\n{body}\n\t\t</property>'


def items_xml(items):
    out = ["<configs>",
           f"\t<!-- {P.get('display_name', NAME)}: generated by Visible Clothing's tools/make_mod.py. Needs the",
           "\t     VisibleClothing mod (it hides clothing under armor, uses the game's shader, fits hats to each head). -->"]
    for it in items:
        gi = it["game_item"]
        new = it.get("new_item")
        if new:
            props = [("Extends", new["extends"]), ("CustomIcon", new.get("icon", new["extends"]))]
            if new.get("icon_tint"):
                props.append(("CustomIconTint", new["icon_tint"]))
            if new.get("description"):
                props.append(("DescriptionKey", gi + "Desc"))
            for k, v in (new.get("properties") or {}).items():
                props.append((k, str(v)))
            pl = "\n".join(f'\t\t\t<property name="{k}" value={quoteattr(v)}/>' for k, v in props)
            out += [f"\t<append xpath=\"/items\">",
                    f"\t\t<item name={quoteattr(gi)}>",
                    pl,
                    "\t" + sdcs(it).replace("\n", "\n\t"),
                    "\t\t</item>",
                    "\t</append>"]
        else:
            # an existing clothing item: replace whatever model it had (also Visible Clothing's own, which loads
            # first: keep this mod's folder name sorting after "VisibleClothing")
            out += [f"\t<remove xpath=\"/items/item[@name='{gi}']/property[@class='SDCS']\"/>",
                    f"\t<append xpath=\"/items/item[@name='{gi}']\">",
                    sdcs(it),
                    "\t</append>"]
    out.append("</configs>")
    return "\n".join(out) + "\n"


def localization(items):
    rows = ["Key,File,Type,UsedInMainMenu,NoTranslate,english"]
    esc = lambda s: '"' + s.replace('"', '""') + '"' if ("," in s or '"' in s) else s
    for it in items:
        new = it.get("new_item")
        if not new:
            continue
        rows.append(f"{it['game_item']},items,Item,,,{esc(new.get('name', it['game_item']))}")
        if new.get("description"):
            rows.append(f"{it['game_item']}Desc,items,Item,,,{esc(new['description'])}")
    return "\n".join(rows) + "\n" if len(rows) > 1 else None


def main():
    its = vc_pack.items()
    drawn = [it for it in its.values() if not it.get("merge_into")]   # pants merged into an outfit have no item
    for it in drawn:
        assert it.get("game_item"), f"{it['id']}: set game_item (an existing clothing item or a new item's name)"
    os.makedirs(os.path.join(DIST, "Config"), exist_ok=True)
    os.makedirs(os.path.join(DIST, "Resources"), exist_ok=True)
    open(os.path.join(DIST, "ModInfo.xml"), "w", encoding="utf-8").write(
        '<?xml version="1.0" encoding="UTF-8"?>\n<xml>\n'
        f'\t<Name value={quoteattr(NAME)} />\n'
        f'\t<DisplayName value={quoteattr(P.get("display_name", NAME))} />\n'
        f'\t<Version value={quoteattr(P.get("version", "1.0.0"))} />\n'
        f'\t<Description value={quoteattr((P.get("description", "") + " Requires the Visible Clothing mod.").strip())} />\n'
        f'\t<Author value={quoteattr(P.get("author", ""))} />\n'
        f'\t<Website value={quoteattr(P.get("website", ""))} />\n</xml>\n')
    open(os.path.join(DIST, "Config", "items.xml"), "w", encoding="utf-8").write(items_xml(drawn))
    loc = localization(drawn)
    lp = os.path.join(DIST, "Config", "Localization.txt")
    if loc:
        open(lp, "w", encoding="utf-8").write(loc)
    elif os.path.exists(lp):
        os.remove(lp)
    extra = os.path.join(vc_pack.PACK_DIR, "Config")   # the pack's own XML (recipes, loot, progression, ...)
    if os.path.isdir(extra):
        for f in os.listdir(extra):
            if f.lower() in ("items.xml", "localization.txt"):
                print(f"  {f} in {extra} ignored: generated from pack.json (put extra items in another file)")
                continue
            shutil.copy2(os.path.join(extra, f), os.path.join(DIST, "Config", f))
    src = os.path.join(vc_pack.ROOT, "unity", "BundleOut", vc_pack.BUNDLE)
    if os.path.exists(src):
        shutil.copy2(src, os.path.join(DIST, "Resources", BUNDLE_FILE))
    else:
        print(f"  no bundle yet ({src}): run the build first")
    open(os.path.join(DIST, "README.txt"), "w", encoding="utf-8").write(
        f"{P.get('display_name', NAME)} {P.get('version', '1.0.0')} by {P.get('author', '')}\n\n"
        "A clothing pack for Visible Clothing (7 Days to Die V3.2). Requires the VisibleClothing mod installed too.\n"
        f"Install: extract so you have Mods/{NAME}/ModInfo.xml next to Mods/VisibleClothing/.\n")
    print(f"mod written: {DIST} ({len(drawn)} items)")


if __name__ == "__main__":
    main()
